export function makeBeast(shape) {
  const m = shell(), b = new VoxelBuilder();
  SHAPES[shape](m, b);
  m.root.add(voxelMesh(b, m.mat));
  if (m.hover) m.root.position.y = m.hover;
  return m;
}
