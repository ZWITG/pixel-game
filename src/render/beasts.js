import * as THREE from 'three';
import { VoxelBuilder, vmat, voxelMesh } from './voxel.js';

// Open-world creatures. Each returns what Enemy expects: { group, root, mat }, plus `legs` to
// trot on and `hover` for those that float. Forward is +z, and they're about a tile in size;
// bosses are the same kind of model, simply made huge.
function shell() {
  const group = new THREE.Group(), root = new THREE.Group(), mat = vmat();
  group.add(root);
  return { group, root, mat };
}

// A leg that swings from the hip.
function leg(m, x, y, z, draw) {
  const pivot = new THREE.Group();
  pivot.position.set(x, y, z);
  const b = new VoxelBuilder();
  draw(b);
  pivot.add(voxelMesh(b, m.mat));
  m.root.add(pivot);
  (m.legs ??= []).push(pivot);
}

